#!/usr/bin/env node
// One-time (or key-rotation) setup for V3 web-push reminders. Generates a VAPID
// keypair, writes the PUBLIC key to public/js/vapid.js (client) and
// src/vapidPublicKey.js (Worker), then pipes the PRIVATE key straight into
// `wrangler secret put VAPID_PRIVATE_KEY` via stdin. The private key is never
// logged, written to disk, or returned to the caller.
import webpush from 'web-push';
const { generateVAPIDKeys } = webpush;
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { spawn } from 'node:child_process';

const { publicKey, privateKey } = generateVAPIDKeys();

const clientPath = fileURLToPath(new URL('../public/js/vapid.js', import.meta.url));
const workerPath = fileURLToPath(new URL('../src/vapidPublicKey.js', import.meta.url));

writeFileSync(
  clientPath,
  `// Generated by scripts/setup-vapid.mjs — safe to commit, this is the PUBLIC VAPID key.\nwindow.VAPID_PUBLIC_KEY = ${JSON.stringify(publicKey)};\n`
);

writeFileSync(
  workerPath,
  `// Generated by scripts/setup-vapid.mjs — safe to commit, this is the PUBLIC VAPID key.\n// The matching private key lives ONLY in the VAPID_PRIVATE_KEY Worker secret.\nexport const VAPID_PUBLIC_KEY = ${JSON.stringify(publicKey)};\n`
);

console.log('Wrote the public VAPID key to public/js/vapid.js and src/vapidPublicKey.js.');
console.log('Piping the private key into `wrangler secret put VAPID_PRIVATE_KEY` (never printed)...');

const child = spawn('npx', ['wrangler', 'secret', 'put', 'VAPID_PRIVATE_KEY'], { stdio: ['pipe', 'inherit', 'inherit'] });
child.stdin.write(privateKey);
child.stdin.end();
child.on('exit', (code) => {
  if (code === 0) console.log('Done — VAPID_PRIVATE_KEY secret set, redeploy to pick it up.');
  process.exit(code ?? 0);
});
